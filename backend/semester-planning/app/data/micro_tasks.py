from dataclasses import dataclass


@dataclass(frozen=True)
class ModuleInfo:
    id: str
    name: str
    course: str


@dataclass(frozen=True)
class MicroTask:
    id: str
    module: str
    title: str
    action: str
    done: str
    weeks: int
    kind: str
    core: bool
    skills: tuple[str, ...]
    prerequisites: tuple[str, ...] = ()
    example: str = ""
    why: str = ""
    hours: int = 2
    # 自定义任务自带模块名（如「Java 夯实」），优先于 MODULES 里的通用名称
    label: str = ""

    def to_prompt(self) -> dict:
        return {
            "id": self.id,
            "module": self.module,
            "title": self.title,
            "action": self.action,
            "done": self.done,
            "weeks": self.weeks,
            "kind": self.kind,
            "prerequisites": list(self.prerequisites),
        }


